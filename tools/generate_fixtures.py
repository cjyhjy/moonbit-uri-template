#!/usr/bin/env python3
"""Compile unchanged, pinned upstream JSON into backend-independent blackbox tests."""
import hashlib
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILES = ('spec-examples.json', 'spec-examples-by-section.json', 'extended-tests.json', 'negative-tests.json')
COMMIT = '4171dac22aa67fc710b3f6df308a50bd08552986'

def quote(s):
    return re.sub(r'\\u([0-9a-fA-F]{4})', r'\\u{\1}', json.dumps(s, ensure_ascii=False))

def scalar(v):
    if isinstance(v, str): return v
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, (int, float)): return json.dumps(v, separators=(',', ':'))
    raise ValueError(f'unsupported fixture scalar {v!r}')

def value(v):
    if v is None: return None
    if isinstance(v, list):
        return '@lib.List([' + ', '.join(quote(scalar(x)) for x in v if x is not None) + '])'
    if isinstance(v, dict):
        pairs = ', '.join('(' + quote(k) + ', ' + quote(scalar(x)) + ')' for k, x in v.items() if x is not None)
        return '@lib.Assoc(@lib.OrderedEntries::from_entries([' + pairs + ']).unwrap())'
    return '@lib.Scalar(' + quote(scalar(v)) + ')'

lines = ['// Generated by tools/generate_fixtures.py; do not edit.', '// Upstream scalar numbers/bools use JSON text; null is undefined.', '']
manifest = {'commit': COMMIT, 'files': {}, 'tests': []}
for file_index, filename in enumerate(FILES):
    path = ROOT / 'testdata/upstream' / filename
    groups = json.loads(path.read_text())
    manifest['files'][filename] = {'sha256': hashlib.sha256(path.read_bytes()).hexdigest(), 'count': 0}
    for group_index, (group, suite) in enumerate(groups.items()):
        helper = f'fixture_{file_index}_{group_index}'
        lines += [f'fn {helper}() -> @lib.Variables {{', '  let vars = @lib.Variables::new()']
        for name, v in suite['variables'].items():
            expr = value(v)
            if expr is not None: lines.append(f'  vars.set({quote(name)}, {expr})')
        lines += ['  vars', '}', '']
        level = suite.get('level', 4)
        for case_index, (template, expected) in enumerate(suite['testcases']):
            test_id = f'{filename}/{group_index}/{case_index}/L{level}'
            lines += [f'test {quote(test_id)} {{', f'  let result = @lib.expand({quote(template)}, {helper}())']
            if expected is False:
                lines += ['  match result {', '    Err(_) => ()', '    Ok(actual) => fail("expected rejection, got: " + actual)', '  }']
            else:
                alternatives = expected if isinstance(expected, list) else [expected]
                lines += ['  match result {', '    Err(e) => fail(e.code + ": " + e.message)', '    Ok(actual) => {', '      let expected : Array[String] = [' + ', '.join(map(quote, alternatives)) + ']', '      assert_true(expected.contains(actual), msg="unexpected expansion: " + actual)', '    }', '  }']
            lines += ['}', '']
            manifest['tests'].append({'id': test_id, 'file': filename, 'group': group, 'level': level, 'negative': expected is False})
            manifest['files'][filename]['count'] += 1
# Format in memory with one process. `moon fmt -- -w FILE` forwards FILE to
# every package formatter, making multiple processes overwrite the same file.
formatted = subprocess.run(
    [str(ROOT/'tools/moonfmt'), '-'], input='\n'.join(lines),
    text=True, stdout=subprocess.PIPE, check=True,
).stdout
(ROOT / 'conformance_test.mbt').write_text(formatted, encoding='utf-8')
(ROOT / 'testdata/manifest.json').write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + '\n')
print(f"Generated {len(manifest['tests'])} upstream tests")
